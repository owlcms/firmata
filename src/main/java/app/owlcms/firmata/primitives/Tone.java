package app.owlcms.firmata.primitives;

import java.util.ArrayList;
import java.util.List;
import java.util.stream.Collectors;

import org.firmata4j.Pin;
import org.slf4j.LoggerFactory;

import app.owlcms.firmata.refdevice.Interruptible;
import app.owlcms.firmata.refdevice.RefDevice;
import ch.qos.logback.classic.Level;
import ch.qos.logback.classic.Logger;

public class Tone {
	/** Firmata at 57600 baud: 10 bits per byte on the wire, 3 bytes per digital port message. */
	private static final double PORT_MESSAGES_PER_SECOND = 57600 / 10.0 / 3;
	/** Headroom for the other traffic (LEDs, etc.) and timing jitter. */
	private static final double SERIAL_BUDGET = 0.8;

	final Logger logger = (Logger) LoggerFactory.getLogger(Tone.class);

	private int frequency;
	private int msDuration;
	private List<Pin> pins;

	private RefDevice board;
	private long lastValue = -1;

	/**
	 * @param pins all the pins are driven in phase by a single loop (e.g. all the referee buzzers when summoning
	 *             all referees)
	 */
	public Tone(int frequency, int msDuration, List<Pin> pins, RefDevice board) {
		this.frequency = frequency;
		this.msDuration = msDuration;
		this.pins = pins;
		this.board = board;
		logger.setLevel(Level.DEBUG);
	}

	public List<String> nanoTimes = new ArrayList<>();

	public void playWait(Interruptible parent) throws InterruptedException {
		double upDuration;
		long nbFullCycles;
		long squareNanos;

		int playedFrequency = frequency;
		if (frequency == 0) {
			// 250Hz silence
			upDuration = (1.0D / 250) / 2;
			nbFullCycles = 250;
			squareNanos = Math.round((upDuration) * 1_000_000_000);
		} else {
			long nbPorts = Math.max(1, pins.stream().map(p -> p.getIndex() / 8).distinct().count());
			playedFrequency = playableFrequency(frequency, nbPorts);
			if (playedFrequency != frequency) {
				logger.debug("pins {} frequency {} lowered to {} to fit the serial link ({} ports)", pinIndexes(),
				        frequency, playedFrequency, nbPorts);
			}
			upDuration = (1.0D / playedFrequency) / 2;
			nbFullCycles = (long) ((msDuration / 1000D) * playedFrequency);
			squareNanos = Math.round((upDuration) * 1_000_000_000);
		}

		var start = System.nanoTime();
		logger.debug("pins {} frequency {} upDuration {}s nanos {}ns cycles {}", pinIndexes(), playedFrequency,
		        Double.toString(upDuration), squareNanos, nbFullCycles);

		try {
			for (int i = 0; i < nbFullCycles; i++) {
				var curStart = System.nanoTime();
				setPins(frequency > 0 ? 1 : 0);
				while (System.nanoTime() < curStart + squareNanos) {
					if (parent.isInterrupted()) {
						return;
					}
					Thread.yield();
				}

				setPins(0);
				curStart = System.nanoTime();
				while (System.nanoTime() < curStart + squareNanos) {
					if (parent.isInterrupted()) {
						return;
					}
					Thread.yield();
				}
			}
		} catch (IllegalStateException e) {
			logger.error("exception {}", e);
		} finally {
			long arg1 = System.nanoTime() - start;
			logger.debug("done {}ns nano cycle average {}", arg1, (1.0D * arg1) / nbFullCycles);
			try {
				board.pinsSetValue(pins, 0);
			} catch (IllegalStateException e) {
			}
		}
		return;
	}

	/**
	 * The square wave is generated by the host, so each half-period costs one serial message per port. A frequency
	 * the serial link cannot sustain comes out slower and distorted, so it is lowered by octaves until it fits.
	 *
	 * @return the frequency, or a lower octave of it
	 */
	static int playableFrequency(int frequency, long nbPorts) {
		double maxFrequency = PORT_MESSAGES_PER_SECOND * SERIAL_BUDGET / (2 * Math.max(1, nbPorts));
		double played = frequency;
		while (played > maxFrequency) {
			played = played / 2;
		}
		return (int) Math.round(played);
	}

	private String pinIndexes() {
		return pins.stream().map(p -> Byte.toString(p.getIndex())).collect(Collectors.joining(","));
	}

	/**
	 * Skip writes that do not change the value (e.g. during a pause) to spare the serial link.
	 */
	private void setPins(long value) {
		if (value != lastValue) {
			board.pinsSetValue(pins, value);
			lastValue = value;
		}
	}

}
